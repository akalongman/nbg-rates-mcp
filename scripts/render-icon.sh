#!/usr/bin/env bash
# Renders every raster from assets/icon.svg and assets/og.svg with librsvg:
# assets/icon.png (512x512, the Claude Desktop extension icon) and
# src/shell/site/assets.generated.ts, which carries the rasters the site
# serves as base64 (icon 512, apple touch icon 180, favicon.ico with the 16,
# 32 and 48 pixel images, share card 1200x630) and the SHA-256 of each SVG
# they came from. Both outputs are committed, so a build needs no renderer;
# run this after editing either SVG. Needs rsvg-convert and ImageMagick's
# convert (Debian and Ubuntu: librsvg2-bin, imagemagick). The SVGs draw
# their text as paths (scripts/glyph-paths.py), so no font is needed.
set -euo pipefail
cd "$(dirname "$0")/.."

module=src/shell/site/assets.generated.ts
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

# Render and hash one snapshot of each source, so the recorded hash is of
# the bytes that were rendered even if an SVG changes while this runs.
cp assets/icon.svg assets/og.svg "$work/"
for size in 512 180 48 32 16; do
    rsvg-convert --width "$size" --height "$size" --output "$work/icon-$size.png" "$work/icon.svg"
done
rsvg-convert --width 1200 --height 630 --output "$work/og.png" "$work/og.svg"
convert "$work/icon-16.png" "$work/icon-32.png" "$work/icon-48.png" "$work/favicon.ico"

# Assignments, not substitutions inside echo, so set -e stops on a failure.
icon_svg_sha256=$(sha256sum "$work/icon.svg" | cut -d ' ' -f 1)
og_svg_sha256=$(sha256sum "$work/og.svg" | cut -d ' ' -f 1)
icon_png=$(base64 -w0 "$work/icon-512.png")
apple_touch_icon_png=$(base64 -w0 "$work/icon-180.png")
favicon_ico=$(base64 -w0 "$work/favicon.ico")
og_png=$(base64 -w0 "$work/og.png")
{
    echo '// Generated by scripts/render-icon.sh from assets/icon.svg and assets/og.svg. Do not edit; run the script.'
    echo "export const ICON_SVG_SHA256 = '$icon_svg_sha256';"
    echo "export const OG_SVG_SHA256 = '$og_svg_sha256';"
    echo "export const ICON_PNG_BASE64 = '$icon_png';"
    echo "export const APPLE_TOUCH_ICON_PNG_BASE64 = '$apple_touch_icon_png';"
    echo "export const FAVICON_ICO_BASE64 = '$favicon_ico';"
    echo "export const OG_PNG_BASE64 = '$og_png';"
} > "$work/assets.generated.ts"

# Every render succeeded; only now replace the committed outputs.
cp "$work/icon-512.png" assets/icon.png
mkdir -p "$(dirname "$module")"
cp "$work/assets.generated.ts" "$module"
echo "rendered assets/icon.png (512x512)"
echo "wrote $module: icon 512x512, apple touch icon 180x180, favicon.ico 16, 32 and 48, share card 1200x630"
